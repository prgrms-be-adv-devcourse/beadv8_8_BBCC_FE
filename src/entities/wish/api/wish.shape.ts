import { arr, bool, nullable, num, obj, oneOf, str } from '@/shared/api'

export const wishRequestShape = obj({
  requestId: str,
  type: str,
  childId: str,
  status: oneOf(['REQUESTED', 'PAID', 'REJECTED', 'CANCELLED', 'EXPIRED']),
  requestedByType: oneOf(['MEMBER', 'CHILD']),
  requestedById: str,
  message: nullable(str),
  requestedAt: str,
  payerType: nullable(str),
  payerId: nullable(str),
  paidAt: nullable(str),
  rejectReason: nullable(oneOf(['TOO_EXPENSIVE', 'ALREADY_HAVE', 'NEXT_TIME', 'OTHER'])),
  rejectedAt: nullable(str),
  cancelReason: nullable(str),
  cancelledAt: nullable(str),
  expiresAt: nullable(str),
  expiredAt: nullable(str),
  items: arr(
    obj({
      cartItemId: nullable(str),
      optionId: str,
      productId: nullable(str),
      sellerId: nullable(str),
      productName: nullable(str),
      optionName: nullable(str),
      size: nullable(str),
      sellerName: nullable(str),
      quantity: num,
      unitPrice: nullable(num),
      purchasable: bool,
      saleStatus: nullable(str),
      purchased: bool,
    }),
  ),
  purchases: arr(obj({ orderId: str, cartItemId: nullable(str), quantity: num, purchasedAt: str })),
  paidOrderItemIds: arr(str),
})
export const wishRequestsShape = arr(wishRequestShape)
export const wishTimelineShape = obj({
  requestId: str,
  status: str,
  rejectReason: nullable(str),
  cancelReason: nullable(str),
  orderIds: arr(str),
  steps: arr(obj({ step: str, status: oneOf(['DONE', 'WAITING']), at: nullable(str) })),
  cancelledBy: nullable(str),
})
